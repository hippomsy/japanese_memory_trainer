/// 문장에 나오는 주요 단어를 나오는 순서대로 돌려준다(긴 말부터 찾아 겹치지 않게).
List<SbWord> sbWordsFor(String japanese) {
  final sorted = [..._w]..sort((a, b) => b.match.length.compareTo(a.match.length));
  final used = List<bool>.filled(japanese.length, false);
  final found = <(int, SbWord)>[];
  final seen = <String>{};
  for (final w in sorted) {
    var from = 0;
    while (true) {
      final i = japanese.indexOf(w.match, from);
      if (i < 0) break;
      from = i + 1;
      var free = true;
      for (var k = i; k < i + w.match.length; k++) {
        if (used[k]) {
          free = false;
          break;
        }
      }
      if (!free) continue;
      for (var k = i; k < i + w.match.length; k++) {
        used[k] = true;
      }
      if (seen.add(w.word)) found.add((i, w));
    }
  }
  found.sort((a, b) => a.$1.compareTo(b.$1));
  return [for (final f in found) f.$2];
}
