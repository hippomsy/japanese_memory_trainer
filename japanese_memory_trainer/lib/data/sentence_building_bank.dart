class SbItem {
  const SbItem(this.ko, this.chunks, this.key, this.wrongs, this.reading);

  /// 한국어 뜻(배열할 때 보는 문제).
  final String ko;

  /// 정답 순서의 일본어 조각.
  final List<String> chunks;

  /// 문법 포인트가 들어 있는 조각 번호(빈칸 문제의 빈칸).
  final int key;

  /// [key] 조각 대신 들어갈 수 있는 틀린 보기 3개(배열에서는 함정 조각 1개로 섞음).
